-- =====================================================
-- PRODUCT ENRICHMENTS
-- AI-generated product information and metadata
-- =====================================================

CREATE TABLE IF NOT EXISTS product_enrichments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_code VARCHAR(100) NOT NULL UNIQUE,

    description TEXT NOT NULL,

    use_cases JSONB NOT NULL,
    target_users JSONB NOT NULL,
    key_features JSONB NOT NULL,
    limitations JSONB NOT NULL,

    normalized_attributes JSONB NOT NULL,

    status VARCHAR(50) NOT NULL DEFAULT 'pending',

    model_name VARCHAR(100),
    prompt_version VARCHAR(50),
    source_hash VARCHAR(128),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_product_enrichments_product
        FOREIGN KEY (product_code)
        REFERENCES products(product_code)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_product_enrichments_status
    ON product_enrichments(status);

CREATE INDEX IF NOT EXISTS idx_product_enrichments_product_code
    ON product_enrichments(product_code);