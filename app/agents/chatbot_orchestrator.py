
from __future__ import annotations

import logging
from dataclasses import dataclass

from app.agents.agent_executor import AgentExecutor
from app.agents.chat_context_builder import ChatContextBuilder
from app.agents.schemes.agent_execution_result import AgentExecutionResult
from app.services.conversation_service import ConversationService


logger = logging.getLogger(__name__)


@dataclass(slots=True)
class ChatbotResult:
    """
    Represent the final result returned by the chatbot.

    This DTO separates the internal execution process from the
    response returned to the API or messaging channel.
    """

    # ID of the conversation containing this interaction.
    conversation_id: str

    # Final answer generated by the AI.
    answer: str

    # Names of the tools executed during this interaction.
    tool_calls: list[str]

    # ID of the user message associated with this request.
    user_message_id: str

    # ID of the persisted final assistant message.
    assistant_message_id: str

    # Optional ID linking the conversation to an external channel.
    channel_conversation_id: int | None = None


class ChatbotOrchestrator:
    """
    Coordinate the chatbot request lifecycle.

    Responsibilities:
    1. Build the conversation context.
    2. Execute the AI agent.
    3. Persist the final assistant answer.
    4. Return a structured result to the caller.

    Tool execution, AI communication, and message-history construction
    are delegated to their respective components.
    """

    def __init__(
        self,
        *,
        context_builder: ChatContextBuilder,
        agent_executor: AgentExecutor,
        conversation_service: ConversationService,
    ) -> None:
        """
        Initialize the orchestrator with its dependencies.

        Args:
            context_builder:
                Builds the conversation context and AI message history.

            agent_executor:
                Runs the AI/tool execution loop and produces the answer.

            conversation_service:
                Persists the final assistant message.
        """

        self.context_builder = context_builder
        self.agent_executor = agent_executor
        self.conversation_service = conversation_service

    def chat(
        self,
        message: str,
        conversation_id: str | None = None,
        *,
        user_id: str | None = None,
        channel: str | None = None,
        channel_chat_id: str | None = None,
        channel_thread_id: str = "",
        channel_user_id: str | None = None,
        channel_message_id: str | None = None,
        request_id: str | None = None,
    ) -> ChatbotResult:
        """
        Process a user message and return the final chatbot response.

        The method coordinates the request but delegates the actual
        context preparation, AI execution, and persistence operations
        to dedicated components.
        """

        logger.info(
            "Chat request started: request_id=%s conversation_id=%s "
            "user_id=%s channel=%s",
            request_id,
            conversation_id,
            user_id,
            channel or "web",
        )

        # Step 1: Build the context for this request.
        #
        # The context builder handles conversation preparation and
        # returns the conversation ID, user message ID, channel
        # conversation ID, and formatted AI message history.
        try:
            context = self.context_builder.build(
                message=message,
                conversation_id=conversation_id,
                user_id=user_id,
                channel=channel or "web",
                channel_chat_id=channel_chat_id,
                channel_thread_id=channel_thread_id,
                channel_user_id=channel_user_id,
                channel_message_id=channel_message_id,
            )

            logger.info(
                "Chat context prepared: request_id=%s "
                "conversation_id=%s user_message_id=%s "
                "history_count=%s",
                request_id,
                context.conversation_id,
                context.user_message_id,
                context.history_count,
            )

        except Exception:
            logger.exception(
                "Failed to prepare chat context: request_id=%s "
                "conversation_id=%s",
                request_id,
                conversation_id,
            )
            raise

        # Step 2: Execute the AI agent.
        #
        # AgentExecutor manages the AI/tool loop until it obtains
        # the final answer or encounters an execution error.
        try:
            execution_result: AgentExecutionResult = (
                self.agent_executor.invoke(
                    messages=context.messages,
                    conversation_id=context.conversation_id,
                )
            )

            logger.info(
                "Agent execution completed: request_id=%s "
                "conversation_id=%s tool_count=%s answer_length=%s",
                request_id,
                context.conversation_id,
                len(execution_result.tool_calls),
                len(execution_result.answer),
            )

        except Exception:
            logger.exception(
                "Agent execution failed: request_id=%s "
                "conversation_id=%s",
                request_id,
                context.conversation_id,
            )
            raise

        # Step 3: Persist the final assistant answer.
        #
        # Tool-call messages and tool results are handled separately
        # by ToolCallHandler. This operation saves the final response
        # intended for the user.
        try:
            assistant_message = (
                self.conversation_service.save_assistant_message(
                    conversation_id=context.conversation_id,
                    content=execution_result.answer,
                )
            )

            assistant_message_id = str(assistant_message["id"])

            logger.info(
                "Assistant answer persisted: request_id=%s "
                "conversation_id=%s assistant_message_id=%s",
                request_id,
                context.conversation_id,
                assistant_message_id,
            )

        except Exception:
            logger.exception(
                "Failed to persist assistant answer: request_id=%s "
                "conversation_id=%s",
                request_id,
                context.conversation_id,
            )
            raise

        # Step 4: Return a stable result DTO to the API or channel adapter.
        #
        # The caller does not need to know how context preparation,
        # AI execution, or database persistence was implemented.
        result = ChatbotResult(
            conversation_id=context.conversation_id,
            answer=execution_result.answer,
            tool_calls=execution_result.tool_calls,
            user_message_id=context.user_message_id,
            assistant_message_id=assistant_message_id,
            channel_conversation_id=context.channel_conversation_id,
        )

        logger.info(
            "Chat request completed: request_id=%s conversation_id=%s "
            "assistant_message_id=%s",
            request_id,
            result.conversation_id,
            result.assistant_message_id,
        )

        return result
